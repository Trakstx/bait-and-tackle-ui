"""Compose a candidate from hash-pinned vendor seed + exact checked-in app source."""
import argparse, hashlib, json, shutil, zipfile
from pathlib import Path
from build_native import TARGETS, sha
ROOT = Path(__file__).resolve().parents[1]
SEED_SHA = '9c637eebb8801a5476eb2640950f008e14ef81720c4dfdbbe8ceb1f79846fa6e'

def compose(seed, native, output, runtime):
    seed = Path(seed).resolve(); native = Path(native).resolve(); output = Path(output).resolve()
    if sha(seed) != SEED_SHA: raise ValueError('Vendor seed archive hash mismatch')
    if output.exists(): raise ValueError('Use a new empty output directory')
    output.mkdir(parents=True)
    with zipfile.ZipFile(seed) as archive:
        for member in archive.infolist():
            target = (output/member.filename).resolve()
            if not target.is_relative_to(output): raise ValueError('Unsafe seed member')
        archive.extractall(output)
    roots = list(output.glob('*/install.py'))
    if len(roots) != 1: raise ValueError('Unexpected seed root')
    package = roots[0].parent; payload = package/'payload'; hud = payload/'BFT_HUD'
    # Seed maps/skin/vendor assets only. Replace the runtime and every custom binary.
    for old in hud.iterdir():
        if old.is_file(): old.unlink()
    for old in (package/'developer-source').iterdir():
        if old.is_file(): old.unlink()
    for item in (ROOT/'src/HUD').iterdir():
        if item.name in ('__pycache__', 'runtime', 'maps'): continue
        if item.is_file(): shutil.copy2(item, hud/item.name)
        elif item.name == 'shaders': shutil.copytree(item, hud/item.name, dirs_exist_ok=True)
    for name in TARGETS: shutil.copy2(native/name, hud/name)
    for item in (ROOT/'src/native-and-tests').iterdir():
        if item.is_file() and item.suffix in ('.cpp', '.hpp', '.py'): shutil.copy2(item, package/'developer-source'/item.name)
    for name in ('install.py', 'process_check.py', 'recover.py'): shutil.copy2(ROOT/'src'/name, package/name)
    old_runtime=hud/'runtime'
    if not old_runtime.resolve().is_relative_to(package.resolve()):raise ValueError('Unsafe runtime destination')
    shutil.rmtree(old_runtime)
    shutil.copytree(Path(runtime).resolve(),old_runtime)
    shutil.copy2(ROOT/'src/python314._pth', old_runtime/'python314._pth')
    shutil.copy2(native/'native-build.json', package/'native-build.json')
    # Do not ship caches generated by verification.
    for cache in sorted(package.rglob('__pycache__'), reverse=True): shutil.rmtree(cache)
    for cache in package.rglob('*.pyc'): cache.unlink()
    files = {str(f.relative_to(payload)).replace('\\','/'): sha(f) for f in sorted(payload.rglob('*')) if f.is_file()}
    manifest = json.loads((package/'manifest.json').read_text(encoding='utf8'))
    manifest['files'] = files
    manifest['version']='0.7.1-candidate'
    manifest['channel'] = 'security-candidate-not-live-validated'
    (package/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf8')
    (package/'CANDIDATE-NOTICE.txt').write_text('Security candidate only. Not the public v0.7.0 artifact. Requires live privilege/capture/HUD validation and a separate P1999 permission decision. See SECURITY-CANDIDATE.md.\n', encoding='utf8')
    receipt = {'seed_sha256': SEED_SHA, 'source_files': {}, 'payload_files': len(files),
               'native_receipt_sha256': sha(native/'native-build.json')}
    for base in [ROOT/'src/HUD', ROOT/'src/native-and-tests']:
        for f in sorted(base.rglob('*')):
            if f.is_file() and '__pycache__' not in f.parts and f.suffix != '.pyc' and not (base.name=='HUD' and 'maps' in f.relative_to(base).parts):
                receipt['source_files'][str(f.relative_to(ROOT)).replace('\\','/')] = sha(f)
    for name in ('install.py','process_check.py','recover.py','python314._pth','Install Bait and Tackle.cmd','Recover Bait and Tackle.cmd'):
        f=ROOT/'src'/name; receipt['source_files']['src/'+name]=sha(f)
    (package/'source-package.json').write_text(json.dumps(receipt, indent=2)+'\n', encoding='utf8')
    shutil.copy2(ROOT/'src/Install Bait and Tackle.cmd',package/'Install Bait and Tackle.cmd')
    shutil.copy2(ROOT/'src/Recover Bait and Tackle.cmd',package/'Recover Bait and Tackle.cmd')
    for name in ('SECURITY-CANDIDATE.md','DEPENDENCIES.md','RECOVERY.md','NETWORK-PRIVACY.md','MinGW-w64-runtime.txt'):
        shutil.copy2(ROOT/'docs'/name,package/name)
    shutil.copy2(ROOT/'docs/THIRD_PARTY_NOTICES.md',package/'THIRD_PARTY_NOTICES.md')
    from dependency_inventory import generate
    generate(package)
    return package

if __name__ == '__main__':
    p=argparse.ArgumentParser(); p.add_argument('--seed', required=True); p.add_argument('--native', required=True); p.add_argument('--output', required=True)
    p.add_argument('--runtime',required=True)
    a=p.parse_args(); print(compose(a.seed, a.native, a.output,a.runtime))
